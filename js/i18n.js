// ---------- language choice ----------

function detectBrowserLanguage() {
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  return /^da\b/i.test(prefs[0]) ? 'da' : 'en';
}

function resolveLanguage(pref) {
  return pref === 'da' || pref === 'en' ? pref : detectBrowserLanguage();
}

let currentLang = document.documentElement.lang === 'da' ? 'da' : 'en';
let languageApplied = false;

function t(key, vars) {
  const text = STRINGS[currentLang]?.[key] ?? STRINGS.en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? vars[name] : whole)) : text;
}

function formatDateTime(iso) {
  return new Date(iso).toLocaleString(currentLang === 'da' ? 'da-DK' : 'en-GB', { dateStyle: 'medium', timeStyle: 'short' });
}

// Fills in every static element that has a data-i18n* attribute.
function applyLanguage() {
  document.documentElement.lang = currentLang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  document.dispatchEvent(new Event('langchange'));
}

// Switches language (and re-renders anything that listens for `langchange`). No-op if nothing changed.
function setLanguage(code) {
  if (languageApplied && code === currentLang) return;
  currentLang = code;
  languageApplied = true;
  applyLanguage();
}
